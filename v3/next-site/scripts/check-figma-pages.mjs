import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const read=p=>readFile(new URL('../'+p,import.meta.url),'utf8');
const data=JSON.parse(await read('../designs/figma-data.json'));
const find=(n,id)=>n.id===id?n:(n.children||[]).map(c=>find(c,id)).find(Boolean);
const video=data.nodes['145:215'].document;
const box=find(video,'254:38').absoluteBoundingBox;
const placeholder=find(video,'145:332').absoluteBoundingBox;
assert.equal(box.width,1840);assert.equal(box.height,1036);
assert.equal(placeholder.x-box.x,94);assert.equal(placeholder.y-box.y,671);
const css=await read('src/integration/figma-layout.css');
assert(css.includes('max-width:1920px')&&css.includes('100cqw/1920px'),'Use capped content width, not unbounded viewport scale');
assert(css.includes('left:94px;top:671px;width:1652px;height:66px'),'Player label uses Figma placeholder slot');
const type=await read('src/integration/typography.css');
assert(!type.includes('[data-react-motion]')&&!type.includes('!important'),'No feature-page typography applied to Figma home');
const runtime=await read('src/generated/scroll-runtime.js');
assert(runtime.includes('Math.min(1,w/1920')&&runtime.includes('scope.clientWidth'),'Home never enlarges artwork beyond source');
const alignment=await read('src/useFontAlignment.js');
assert(alignment.includes('el.getBoundingClientRect().width/parseFloat(style.width)'),'Font calibration uses actual node scale');
const motion=await read('src/MotionExperience.jsx');
assert(motion.includes('markReady:false')&&motion.includes('calibrationEpoch={epoch}'),'Home calibration preserves interaction-ready lifecycle');
console.log('PASS: Figma home typography, source-size video cap, player slot and actual-scale font calibration');
